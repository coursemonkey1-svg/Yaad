  /// Localised 3-letter month abbreviation for summary/review titles.
  String monthAbbr(int month) {
    const en = [
      'Jan', 'Feb', 'Mar', 'Apr', 'May', 'Jun',
      'Jul', 'Aug', 'Sep', 'Oct', 'Nov', 'Dec'
    ];
    const ur = [
      'جنوری', 'فروری', 'مارچ', 'اپریل', 'مئی', 'جون',
      'جولائی', 'اگست', 'ستمبر', 'اکتوبر', 'نومبر', 'دسمبر'
    ];
    final list = code == 'ur' ? ur : en;
    return list[month - 1];
  }

  /// Non-asserting lookup: returns null when the key is missing in both
  /// languages. For dynamic keys (e.g. custom purpose ids) where a
  /// fallback is better than a debug assert.
  String? find(String key) {
    final map = code == 'ur' ? _ur : _en;
    return map[key] ?? _en[key];
  }

  /// Fails loudly in debug if a key is missing an Urdu translation.
  String get(String key) {
    final map = code == 'ur' ? _ur : _en;
    final v = map[key];
    assert(v != null, 'Missing "$code" string for key: $key');
    return v ?? _en[key] ?? key;
  }

  /// Every English key must exist in Urdu (checked by tests).
  static bool get urduComplete =>
      _en.keys.every((k) => _ur.containsKey(k));
}
